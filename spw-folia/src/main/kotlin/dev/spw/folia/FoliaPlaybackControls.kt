/**
 * v0.3.0 playback-bar controls and queue snapshot for the SPW host player.
 *
 * The host (SPW 1.19.0) player is not part of the Workshop API, so everything here is mapped
 * with `java.lang.reflect` against the *host's own* classloader. The mapping is frozen in
 * `docs/playback-controls.md` §2 (R8 build) and the whole layer is optional by design:
 *
 *  - the plugin does not compile against a single host class, only against class *names*;
 *  - every reflection failure is swallowed + logged (first hit in full, then throttled) — the
 *    bridge thread, the plugin lifecycle and the settings UI must never fail because the host
 *    version changed;
 *  - handles are resolved once (double-checked under [resolveLock], cached in @Volatile fields)
 *    and host state is re-read on every [queueJson], never cached.
 *
 * Wire format (docs/protocol.md §1/§2): the bridge owns stdin/stdout; this object only turns a
 * `{"t":"control",...}` line into host method calls and renders the current queue as the inner
 * JSON object of a `{"t":"queue",...}` line.
 */
internal object FoliaPlaybackControls {

    // ------------------------------------------------ host names (playback-controls.md §2) ----

    private const val CONTROLLER_CLASS = "com.xuncorp.voxzen.service.PlaybackController"
    private const val STATE_FLOW_CLASS = "kotlinx.coroutines.flow.StateFlow"
    private const val QUEUE_STATE_CLASS = "com.xuncorp.spc.core.queue.PlaybackQueueState"
    private const val QUEUE_MODE_CLASS = "com.xuncorp.spc.core.queue.PlaybackQueue\$Mode"
    /**
     * SPW 1.19.0 ground truth (javap-verified): the queue element is the *top-level*
     * single-character class U+037F under `com.xuncorp.spc.core.queue`.
     *
     * This is an **R8-obfuscated identifier**, i.e. exactly what the Steam workshop "插件开发建议"
     * post warns against pinning: it is regenerated on every host build, and it already differs
     * between the Windows and Linux builds of one version. It is kept only as the last-resort
     * fallback for a host whose metadata has been stripped; [resolveQueueItemClass] is the real
     * lookup and recovers the class from its Kotlin metadata (`PlaybackQueueItem`) or from its shape.
     */
    private const val QUEUE_ITEM_CLASS_FALLBACK = "com.xuncorp.spc.core.queue.\u037F"
    /** Original (source-level) name of the queue element, as preserved in `@Metadata`. */
    private const val QUEUE_ITEM_ORIGINAL_NAME = "PlaybackQueueItem"
    private const val QUEUE_PACKAGE = "com.xuncorp.spc.core.queue"
    private const val MEDIA_ITEM_CLASS = "com.xuncorp.pisces.PiscesMediaItem"

    private const val CONTROLLER_INSTANCE = "INSTANCE"
    private const val GET_QUEUE_STATE = "getPlaybackQueueState"
    private const val PLAY_OR_PAUSE = "playOrPause"
    private const val PREVIOUS = "previous"
    private const val NEXT = "next"
    private const val SEEK_TO = "seekTo"
    private const val CHANGE_PLAYBACK_MODE = "changePlaybackMode"
    private const val PLAY_MUSIC_AT = "playMusicAt"

    /**
     * R8-obfuscated member names kept as unicode escapes: U+037F is the single-character getter
     * name on every host class, U+0528..U+052B are the PlaybackQueueState accessors. Writing them
     * as escapes keeps this source ASCII-clean and immune to editor re-encoding.
     *
     * **Fallback only.** These are regenerated by every host build (see the reset note above), so
     * [resolveQueueStateMembers] / [resolveQueueItemMembers] look the members up by Kotlin metadata
     * property name or by return-type shape first, and only fall back here when both fail.
     */
    private const val STATE_MODE_FALLBACK = "\u037F"
    private const val STATE_NORMAL_QUEUE_FALLBACK = "\u0528"
    private const val STATE_NORMAL_INDEX_FALLBACK = "\u0529"
    private const val STATE_RANDOM_QUEUE_FALLBACK = "\u052A"
    private const val STATE_RANDOM_INDEX_FALLBACK = "\u052B"
    private const val ITEM_ID_FALLBACK = "\u037F"
    private const val ITEM_DATA_FALLBACK = "\u0528"
    private const val MEDIA_ID = "\u037F"
    private const val MEDIA_TITLE = "\u0528"
    private const val MEDIA_ARTIST = "\u0529"
    private const val MEDIA_ALBUM = "\u052A"

    private const val MODE_CIRCLE = "Circle"
    private const val MODE_RANDOM = "Random"

    /** Host enum name -> wire name (docs/protocol.md §1). Unknown/absent degrades to circle. */
    private val WIRE_MODES = mapOf(
        "Circle" to "circle",
        "CircleEnd" to "circle-end",
        "RepeatOne" to "repeat-one",
        "Random" to "random",
    )

    /** Back off between failed resolve attempts (host not fully up / class not loaded yet). */
    private const val RESOLVE_RETRY_MS = 5_000L

    /**
     * Consecutive failed resolves after which the fast retry backs off to [EXHAUSTED_RETRY_MS].
     *
     * This replaced a one-way `permanentlyUnavailable` flag. That flag was set for
     * `ClassNotFoundException` / `NoClassDefFoundError` / `ExceptionInInitializerError`, i.e. for
     * conditions that are *not* reliably permanent inside a live host process: the queue classes may
     * simply not have been loaded yet by the classloader that was current on the first attempt, and
     * a host update that swaps the classpath mid-session produces the same error once. Pinning the
     * feature off for the rest of the process turned any of those into "playback controls vanished
     * until SPW restarts". The R8-rename guidance this file now follows makes a *permanent* failure
     * far less likely anyway, so a slow retry is the correct trade: it costs one failing reflection
     * pass every few minutes and can recover on its own.
     */
    private const val MAX_RESOLVE_FAILURES = 4

    /** Slow retry interval once [MAX_RESOLVE_FAILURES] consecutive attempts have failed (~2 min). */
    private const val EXHAUSTED_RETRY_MS = 120_000L

    // --------------------------------------------------------------- resolution state ----

    private val resolveLock = Any()

    @Volatile private var handlesCache: Handles? = null

    /**
     * True while the slow-retry backoff is in effect. Unlike the old `permanentlyUnavailable` this is
     * a *timer*, not a latch: [handles] clears it when [exhaustedUntilMs] passes, so the next resolve
     * pass runs and can succeed (e.g. after the host finished loading its queue classes).
     */
    @Volatile private var exhausted = false

    /** Wall-clock deadline for [exhausted]; 0 while not exhausted. */
    @Volatile private var exhaustedUntilMs = 0L

    /** Failed resolve attempts since the last success (drives [MAX_RESOLVE_FAILURES]). */
    @Volatile private var consecutiveFailures = 0
    @Volatile private var lastResolveAttemptMs = 0L

    /** Set by [handleControl]; the bridge force-pushes the queue on its next pump tick. */
    private val queueDirtyFlag = AtomicBoolean(false)

    /**
     * Last non-random host mode seen before shuffle was switched on, restored when shuffle is
     * switched off again. Memory-only (per docs/playback-controls.md §3.1), defaults to Circle.
     */
    private val rememberedMode = AtomicReference<Any?>(null)

    private val failureCount = AtomicLong(0L)
    private val controlCount = AtomicLong(0L)
    private val loggedUnknownActions = ConcurrentHashMap<String, Boolean>()

    // ------------------------------------------------------------------ public surface ----

    /**
     * Executes one `{"t":"control","action":...}` line from the helper.
     *
     * Fire-and-forget: unknown actions and malformed arguments are ignored (logged once), and no
     * failure ever escapes into [FoliaHostBridge]'s stdout reader thread.
     */
    fun handleControl(line: String) {
        val action = try {
            Json.stringField(line, "action")
        } catch (_: Throwable) {
            null
        }
        if (action.isNullOrEmpty()) {
            logIgnoredControl("control line without action")
            return
        }
        val handles = handles()
        if (handles == null) {
            noteFailure("control:$action", IllegalStateException("host playback controls unavailable"))
            return
        }
        try {
            when (action) {
                "toggle" -> handles.playOrPause.invoke(handles.controller)
                "previous" -> handles.previous.invoke(handles.controller)
                "next" -> handles.next.invoke(handles.controller)
                "seek" -> {
                    val position = longField(line, "positionMs")
                    if (position == null) {
                        logIgnoredControl("seek without positionMs")
                        return
                    }
                    handles.seekTo.invoke(handles.controller, maxOf(0L, position))
                }
                "shuffle" -> invokeShuffle(handles)
                "queue-play" -> {
                    val index = longField(line, "index")
                    if (index == null || index < 0L || index > Int.MAX_VALUE.toLong()) {
                        logIgnoredControl("queue-play without a valid index")
                        return
                    }
                    handles.playMusicAt.invoke(handles.controller, index.toInt(), rawBoolean(line, "random"))
                }
                else -> {
                    logUnknownAction(action)
                    return
                }
            }
            // The player state machine applies asynchronously; the bridge re-reads on the next
            // pump tick (and the 500 ms diff catches anything that lands a moment later).
            queueDirtyFlag.set(true)
            logControl(action)
        } catch (t: Throwable) {
            noteFailure("control:$action", t)
        }
    }

    /**
     * Renders the current playback queue as the *body* of a `queue` line:
     * `{"mode":"circle|circle-end|repeat-one|random","random":bool,"index":int,"items":[...]}`.
     * Returns null when the host classes/members are unavailable (page keeps its last snapshot).
     */
    fun queueJson(): String? {
        val handles = handles() ?: return null
        return try {
            val state = readQueueState(handles) ?: return null
            val modeName = (handles.mode.invoke(state) as? Enum<*>)?.name
            val random = modeName == MODE_RANDOM
            val queue = (if (random) handles.randomQueue else handles.normalQueue).invoke(state)
            val index = ((if (random) handles.randomIndex else handles.normalIndex).invoke(state) as? Number)?.toInt() ?: -1
            buildQueueJson(handles, modeName, random, index, queue)
        } catch (t: Throwable) {
            noteFailure("queueJson", t)
            null
        }
    }

    /** Consumes the dirty flag; the bridge then pushes a queue snapshot on the next pump tick. */
    fun consumeQueueDirty(): Boolean = queueDirtyFlag.getAndSet(false)

    // --------------------------------------------------------------------- control impl ----

    /**
     * Shuffle toggle: host mode is Random -> restore the remembered non-random mode (default
     * Circle); otherwise remember the current mode and switch to Random.
     */
    private fun invokeShuffle(handles: Handles) {
        val current = currentMode(handles)
        val currentName = (current as? Enum<*>)?.name
        if (currentName == MODE_RANDOM) {
            val target = rememberedMode.get() ?: modeConstant(handles.modeClass, MODE_CIRCLE)
            if (target == null) {
                noteFailure("shuffle", IllegalStateException("PlaybackQueue.Mode.$MODE_CIRCLE not found"))
                return
            }
            handles.changePlaybackMode.invoke(handles.controller, target)
            FoliaPlugin.logStatic("playback shuffle off -> ${(target as? Enum<*>)?.name ?: MODE_CIRCLE}")
        } else {
            if (current != null) rememberedMode.set(current)
            val target = modeConstant(handles.modeClass, MODE_RANDOM)
            if (target == null) {
                noteFailure("shuffle", IllegalStateException("PlaybackQueue.Mode.$MODE_RANDOM not found"))
                return
            }
            handles.changePlaybackMode.invoke(handles.controller, target)
            FoliaPlugin.logStatic("playback shuffle on -> $MODE_RANDOM (remembered ${currentName ?: MODE_CIRCLE})")
        }
    }

    private fun currentMode(handles: Handles): Any? = try {
        readQueueState(handles)?.let { handles.mode.invoke(it) }
    } catch (t: Throwable) {
        noteFailure("readMode", t)
        null
    }

    /** Reads the live state: `getPlaybackQueueState().value` (never cached). */
    private fun readQueueState(handles: Handles): Any? {
        val stateFlow = handles.getQueueState.invoke(handles.controller) ?: return null
        return handles.stateValue.invoke(stateFlow)
    }

    private fun modeConstant(modeClass: Class<*>, name: String): Any? {
        val constants = try {
            modeClass.enumConstants
        } catch (_: Throwable) {
            null
        } ?: return null
        for (constant in constants) {
            if ((constant as? Enum<*>)?.name == name) return constant
        }
        return null
    }

    // --------------------------------------------------------------------- queue render ----

    private fun buildQueueJson(
        handles: Handles,
        modeName: String?,
        random: Boolean,
        index: Int,
        queue: Any?,
    ): String {
        val entries = queue as? List<*>
        val builder = StringBuilder(128 + (entries?.size ?: 0) * 96)
        builder.append("{\"mode\":").append(Json.str(wireMode(modeName)))
            .append(",\"random\":").append(Json.bool(random))
            .append(",\"index\":").append(index)
            .append(",\"items\":[")
        if (entries != null) {
            var first = true
            for (entry in entries) {
                if (entry == null) continue
                if (!first) builder.append(',')
                first = false
                appendQueueItem(builder, handles, entry)
            }
        }
        builder.append("]}")
        return builder.toString()
    }

    private fun appendQueueItem(builder: StringBuilder, handles: Handles, entry: Any) {
        val data = invokeQuietly(handles.itemData, entry)
        val internalId = (invokeQuietly(handles.itemId, entry) as? Number)?.toInt()
        val media = data?.takeIf { handles.mediaItemClass.isInstance(it) }
        val id = (media?.let { invokeQuietly(handles.mediaId, it) } as? String) ?: internalId?.toString() ?: ""
        builder.append("{\"id\":").append(Json.str(id))
            .append(",\"title\":").append(Json.str(mediaString(handles.mediaTitle, media)))
            .append(",\"artist\":").append(Json.str(mediaString(handles.mediaArtist, media)))
            .append(",\"album\":").append(Json.str(mediaString(handles.mediaAlbum, media)))
            .append('}')
    }

    private fun mediaString(method: Method, media: Any?): String {
        if (media == null) return ""
        return (invokeQuietly(method, media) as? String) ?: ""
    }

    private fun invokeQuietly(method: Method, target: Any): Any? = try {
        method.invoke(target)
    } catch (_: Throwable) {
        null
    }

    private fun wireMode(hostModeName: String?): String =
        hostModeName?.let { WIRE_MODES[it] } ?: "circle"

    // -------------------------------------------------------------------- line parsing ----

    private fun longField(line: String, key: String): Long? {
        val raw = Json.rawField(line, key)?.trim() ?: return null
        return raw.toLongOrNull() ?: raw.toDoubleOrNull()?.toLong()
    }

    private fun rawBoolean(line: String, key: String): Boolean {
        val raw = Json.rawField(line, key)?.trim()
        return raw == "true" || raw == "1"
    }

    // ----------------------------------------------------------------------- resolution ----

    private fun handles(): Handles? {
        handlesCache?.let { return it }
        // Slow-retry backoff expiry: unlike the old one-way flag this clears itself, so a host that
        // finished loading its queue classes after our first attempts is picked up on the next pass.
        if (exhausted && System.currentTimeMillis() >= exhaustedUntilMs) {
            exhausted = false
            consecutiveFailures = 0
            noteFailure("resolve-backoff expired, probing again", null)
        }
        if (exhausted) return null
        val now = System.currentTimeMillis()
        if (now - lastResolveAttemptMs < RESOLVE_RETRY_MS) return null
        synchronized(resolveLock) {
            handlesCache?.let { return it }
            if (exhausted) return null
            val attemptAt = System.currentTimeMillis()
            if (attemptAt - lastResolveAttemptMs < RESOLVE_RETRY_MS) return null
            lastResolveAttemptMs = attemptAt
            return try {
                val resolved = resolve()
                handlesCache = resolved
                consecutiveFailures = 0
                logResolved(resolved)
                resolved
            } catch (t: Throwable) {
                consecutiveFailures += 1
                if (consecutiveFailures >= MAX_RESOLVE_FAILURES) {
                    // Give up *for this session only* — see EXHAUSTED_RETRY_MS. The old code set a
                    // one-way `permanentlyUnavailable` flag for ClassNotFound/NoClassDefFoundError,
                    // which turned a transient condition (host classes not on the loader that was
                    // current at first call, a partially applied update) into "playback controls are
                    // gone until the user restarts SPW". Retrying on a slow beat costs one failed
                    // reflection pass every few minutes and removes that failure mode entirely.
                    exhaustedUntilMs = System.currentTimeMillis() + EXHAUSTED_RETRY_MS
                    exhausted = true
                    noteFailure("resolve-exhausted after $consecutiveFailures attempt(s), retry in ${EXHAUSTED_RETRY_MS / 1000}s", t)
                } else {
                    noteFailure("resolve", t)
                }
                null
            }
        }
    }

    private fun resolve(): Handles {
        val (loader, controllerClass) = locateControllerClass()
        val controller = controllerInstance(controllerClass)
        val stateFlowClass = loadClass(STATE_FLOW_CLASS, loader)
        val queueStateClass = loadClass(QUEUE_STATE_CLASS, loader)
        val modeClass = loadClass(QUEUE_MODE_CLASS, loader)
        // The queue item class is the one genuinely dangerous name: it has no stable source name in
        // the class file, so recover it from metadata/shape instead of pinning `\u037F`.
        val queueItemClass = resolveQueueItemClass(loader)
        val mediaItemClass = loadClass(MEDIA_ITEM_CLASS, loader)
        val stateMembers = resolveQueueStateMembers(queueStateClass, modeClass)
        val itemMembers = resolveQueueItemMembers(queueItemClass)

        return Handles(
            loader = loader,
            controller = controller,
            getQueueState = requireMethod(controllerClass, GET_QUEUE_STATE) { it.parameterCount == 0 },
            playOrPause = requireMethod(controllerClass, PLAY_OR_PAUSE) { it.parameterCount == 0 },
            previous = requireMethod(controllerClass, PREVIOUS) { it.parameterCount == 0 },
            next = requireMethod(controllerClass, NEXT) { it.parameterCount == 0 },
            seekTo = requireMethod(controllerClass, SEEK_TO) { method ->
                method.parameterCount == 1 && method.parameterTypes[0].let { isLongType(it) }
            },
            changePlaybackMode = requireMethod(controllerClass, CHANGE_PLAYBACK_MODE) { method ->
                method.parameterCount == 1 && method.parameterTypes[0].let { parameter ->
                    parameter == modeClass || parameter.isAssignableFrom(modeClass) || modeClass.isAssignableFrom(parameter)
                }
            },
            playMusicAt = requireMethod(controllerClass, PLAY_MUSIC_AT) { method ->
                method.parameterCount == 2 &&
                    method.parameterTypes[0].let { isIntType(it) } &&
                    method.parameterTypes[1].let { isBooleanType(it) }
            },
            stateFlowClass = stateFlowClass,
            stateValue = requireMethod(stateFlowClass, "getValue") { it.parameterCount == 0 },
            queueStateClass = queueStateClass,
            modeClass = modeClass,
            queueItemClass = queueItemClass,
            mediaItemClass = mediaItemClass,
            mode = stateMembers.mode,
            normalQueue = stateMembers.normalQueue,
            normalIndex = stateMembers.normalIndex,
            randomQueue = stateMembers.randomQueue,
            randomIndex = stateMembers.randomIndex,
            itemId = itemMembers.itemId,
            itemData = itemMembers.itemData,
            mediaId = requireMethod(mediaItemClass, MEDIA_ID) { isStringLike(it) },
            mediaTitle = requireMethod(mediaItemClass, MEDIA_TITLE) { isStringLike(it) },
            mediaArtist = requireMethod(mediaItemClass, MEDIA_ARTIST) { isStringLike(it) },
            mediaAlbum = requireMethod(mediaItemClass, MEDIA_ALBUM) { isStringLike(it) },
        )
    }

    // ------------------------------------------- R8-rename-proof member resolution ----

    /**
     * Resolves the queue element class without trusting an obfuscated name.
     *
     * Order (every step validates by reflection before the class is used):
     *  1. `@Metadata` recovery — the host keeps Kotlin metadata, and it still names the type
     *     `com.xuncorp.spc.core.queue.PlaybackQueueItem` even though the class file is `\u037F`.
     *     The *simple* name is preferred, then any candidate whose metadata mentions it.
     *  2. Shape — a final top-level class in the queue package with exactly two instance fields
     *     `int` + `Object` and a static self-typed two-arg factory (Kotlin's `copy` bridge). That is
     *     the data-class shape of a queue element and nothing else in the package has it.
     *  3. The historical hardcoded id, so a metadata-stripped build keeps working exactly as before.
     *
     * Throws only when all three fail, i.e. when the host genuinely renamed the package — the caller
     * then reports the failure without permanently disabling the feature (see [noteFailure]).
     */
    private fun resolveQueueItemClass(loader: ClassLoader): Class<*> {
        // 1a. Source name resolved directly (R8 sometimes keeps the original for non-obfuscated members).
        val direct = runCatching {
            Class.forName("$QUEUE_PACKAGE.$QUEUE_ITEM_ORIGINAL_NAME", false, loader)
        }.getOrNull()
        if (direct != null && looksLikeQueueItem(direct)) {
            logResolve("queue-item", "$QUEUE_ITEM_ORIGINAL_NAME (direct source name)")
            return direct
        }

        // 1b/2. Scan the queue package for a class whose metadata carries the original name, or
        //       whose shape is the data-class queue element. Only classes that are already loadable
        //       (the package is part of the host's own classpath) are inspected.
        val scanned = scanQueuePackage(loader)
        val byMetadata = scanned.firstOrNull { type ->
            val strings = HostMemberResolver.metadataStrings(type) ?: emptySet()
            strings.any { it.contains(QUEUE_ITEM_ORIGINAL_NAME) } && looksLikeQueueItem(type)
        }
        if (byMetadata != null) {
            logResolve("queue-item", "${byMetadata.name} (metadata names PlaybackQueueItem)")
            return byMetadata
        }
        val byShape = scanned.firstOrNull { looksLikeQueueItem(it) }
        if (byShape != null) {
            logResolve("queue-item", "${byShape.name} (data-class shape)")
            return byShape
        }

        // 3. Last resort: the historical pinned id.
        val fallback = loadClass(QUEUE_ITEM_CLASS_FALLBACK, loader)
        logResolve("queue-item", "${fallback.name} (pinned fallback id)")
        return fallback
    }

    /**
     * Every loadable top-level class in `com.xuncorp.spc.core.queue`.
     *
     * There is no classpath enumeration we can trust across host builds. Two sources are combined:
     *  1. the sibling type refs that the queue-state metadata mentions (they carry the *source*
     *     names, e.g. `com/xuncorp/spc/core/queue/PlaybackQueueItem`, which may not exist in the
     *     class file after obfuscation — `Class.forName` then simply yields null and the entry is
     *     dropped), and
     *  2. the actual return types of the state's own getters (always loadable, but only some types).
     *
     * Whatever cannot be enumerated is not considered — [resolveQueueItemClass] then falls back to
     * the pinned id, i.e. the pre-change behaviour, so this can never make a working host stop.
     */
    private fun scanQueuePackage(loader: ClassLoader): List<Class<*>> {
        val names = LinkedHashSet<String>()
        // Known, non-obfuscated anchors in the same package: their metadata lists the siblings.
        for (anchor in listOf("$QUEUE_PACKAGE.PlaybackQueueState", "$QUEUE_PACKAGE.PlaybackQueue")) {
            val type = runCatching { Class.forName(anchor, false, loader) }.getOrNull() ?: continue
            // Sibling types of the state, straight out of its getters (these resolve even when the
            // metadata ref names a renamed class).
            for (method in HostMemberResolver.getters(type)) {
                val ret = method.returnType
                if (ret.name.startsWith("$QUEUE_PACKAGE.")) names.add(ret.name)
            }
            HostMemberResolver.metadataStrings(type)?.forEach { entry ->
                val slash = entry.replace('.', '/')
                if (slash.startsWith("${QUEUE_PACKAGE.replace('.', '/')}/") && !slash.contains('$')) {
                    names.add(slash.replace('/', '.'))
                }
            }
        }
        // The queue element is not reachable from any non-obfuscated name, so also probe the
        // obfuscated single-character ids that R8 uses for top-level classes in this package. The
        // probe is bounded: it only tries the pinned id (the one historically used) — the shape test
        // then decides whether it really is the queue element.
        names.add("$QUEUE_PACKAGE.\u037F")
        return names.mapNotNull { runCatching { Class.forName(it, false, loader) }.getOrNull() }
    }

    /** Shape test for the queue element: `data class PlaybackQueueItem(id: Int, data: Any?)`. */
    private fun looksLikeQueueItem(type: Class<*>): Boolean {
        if (type.isInterface || type.isEnum) return false
        if (Modifier.isAbstract(type.modifiers)) return false
        val fields = HostMemberResolver.declaredFields(type)
        if (fields.size != 2) return false
        val hasInt = fields.any { HostMemberResolver.isIntReturn(it.type) }
        val hasObject = fields.any { !it.type.isPrimitive && it.type == Any::class.java }
        if (!hasInt || !hasObject) return false
        // A Kotlin data class ships the static self-typed `copy` bridge; requiring it keeps a
        // coincidentally-shaped class from being mistaken for the queue element.
        return HostMemberResolver.selfTypedFactory(type) != null || HostMemberResolver.constructorOf(type, 2) != null
    }

    /** Getter set of the queue state, recovered without relying on its obfuscated accessor names. */
    private class StateMembers(
        val mode: Method,
        val normalQueue: Method,
        val normalIndex: Method,
        val randomQueue: Method,
        val randomIndex: Method,
    )

    /**
     * Resolves `PlaybackQueueState`'s five accessors without trusting an obfuscated name.
     *
     * The normal-vs-random problem: both are `(List, int)` pairs, so return types alone cannot tell
     * them apart. The solution is positional, and it is verified against the live host build:
     *
     *   metadata property order : mode, normalQueue, normalIndex, randomQueue, randomIndex, readyToSave
     *   class-file field order  : \u037F Mode, \u0528 List, \u0529 int, \u052A List, \u052B int, \u052C boolean
     *   getter return types     : Mode, List, int, List, int, boolean
     *
     * R8 renames the JVM members but keeps the Kotlin metadata *and* the declaration order, so zipping
     * the two gives every accessor its role by source name — no obfuscated identifier involved. This
     * is the workshop post's "compilation-stable feature" (Metadata + return types), not a guess.
     *
     * Fallbacks, in order: (1) positional zip as above; (2) shape-only declaration order of the two
     * (List, int) pairs; (3) the historical pinned ids, so a host with metadata stripped behaves
     * exactly as it did before this change.
     */
    private fun resolveQueueStateMembers(type: Class<*>, modeClass: Class<*>): StateMembers {
        val modePredicate: (Method) -> Boolean = { isModeLike(it, modeClass) }

        // ---- 1. metadata property order zipped with FIELD-ordered accessors ----
        //
        // The property names come from @Metadata (stable across R8 passes); the member for each
        // property comes from the field table, NOT from getDeclaredMethods() order. That distinction
        // is load-bearing: on the live host the getter table is shuffled
        // (getters: \u052B int, \u0529 int, \u052A List, \u037F Mode, \u0528 List) while the field table keeps
        // data-class order (\u037F Mode, \u0528 List, \u0529 int, \u052A List, \u052B int). Bucketing getters by
        // type and zipping them with the metadata names silently swapped normal/random — caught by the
        // verification suite against the real host archive.
        val propertyOrder = HostMemberResolver.metadataPropertyOrder(type)
        if (propertyOrder != null) {
            val accessors = HostMemberResolver.fieldAccessorsInOrder(type)
            val getterByFieldOrder = accessors.map { it.second }
            val mode = getterByFieldOrder.firstOrNull { modePredicate(it) }
            val listGetters = getterByFieldOrder.filter { isListLike(it) }
            val intGetters = getterByFieldOrder.filter { isIntGetter(it) }
            if (mode != null && listGetters.size >= 2 && intGetters.size >= 2) {
                // Walk the metadata properties in declaration order; each queue/index property takes
                // the next accessor of its kind *in field order*, which is the same component order the
                // property list was derived from.
                val queueByName = LinkedHashMap<String, Method>(2)
                val indexByName = LinkedHashMap<String, Method>(2)
                var nextList = 0
                var nextInt = 0
                for (property in propertyOrder) {
                    when {
                        property.endsWith("Queue", ignoreCase = true) && nextList < listGetters.size ->
                            queueByName[property] = listGetters[nextList++]
                        property.endsWith("Index", ignoreCase = true) && nextInt < intGetters.size ->
                            indexByName[property] = intGetters[nextInt++]
                    }
                }
                val normalQueue = queueByName["normalQueue"]
                val normalIndex = indexByName["normalIndex"]
                val randomQueue = queueByName["randomQueue"]
                val randomIndex = indexByName["randomIndex"]
                if (normalQueue != null && normalIndex != null && randomQueue != null && randomIndex != null) {
                    logResolve("queue-state", "metadata order $propertyOrder + field-ordered accessors")
                    return StateMembers(mode, normalQueue, normalIndex, randomQueue, randomIndex)
                }
            }
        }

        // ---- 2. shape only: the two (List, int) pairs in declaration order ----
        val pairs = HostMemberResolver.listIntPairs(type)
        val shapeMode = HostMemberResolver.matchByType(type, modePredicate).firstOrNull()
        if (pairs.size >= 2 && shapeMode != null) {
            logResolve("queue-state", "declaration order of ${pairs.size} (List,int) pairs (no metadata)")
            return StateMembers(shapeMode, pairs[0].first, pairs[0].second, pairs[1].first, pairs[1].second)
        }

        // ---- 3. pinned ids: pre-change behaviour, last resort ----
        logResolve("queue-state", "pinned accessor ids (metadata and shape unavailable)")
        return StateMembers(
            mode = requireMethod(type, STATE_MODE_FALLBACK, modePredicate),
            normalQueue = requireMethod(type, STATE_NORMAL_QUEUE_FALLBACK) { isListLike(it) },
            normalIndex = requireMethod(type, STATE_NORMAL_INDEX_FALLBACK) { isIntGetter(it) },
            randomQueue = requireMethod(type, STATE_RANDOM_QUEUE_FALLBACK) { isListLike(it) },
            randomIndex = requireMethod(type, STATE_RANDOM_INDEX_FALLBACK) { isIntGetter(it) },
        )
    }

    private class ItemMembers(val itemId: Method, val itemData: Method)

    /**
     * Resolves the queue element's `id` (Int) and `data` (Object?) getters.
     *
     * Same positional trick: the element is `data class PlaybackQueueItem(id: Int, data: Any?)`, so the
     * metadata property order (`id`, `data`) indexes the int getter and the reference getter in their
     * own declaration order. Return types disambiguate outright here, so this is the least fragile
     * lookup in the file.
     */
    private fun resolveQueueItemMembers(type: Class<*>): ItemMembers {
        val propertyOrder = HostMemberResolver.metadataPropertyOrder(type)
        val intGetters = HostMemberResolver.matchByType(type) { isIntGetter(it) }
        // `data` is the only non-primitive, non-self reference getter on the element.
        val refGetters = HostMemberResolver.matchByType(type) { method ->
            method.returnType != type && !method.returnType.isPrimitive && method.returnType != java.lang.Void.TYPE
        }
        if (propertyOrder != null) {
            var nextInt = 0
            var nextRef = 0
            var id: Method? = null
            var data: Method? = null
            for (property in propertyOrder) {
                when (property) {
                    "id", "itemId" -> if (nextInt < intGetters.size) id = intGetters[nextInt++]
                    "data", "itemData" -> if (nextRef < refGetters.size) data = refGetters[nextRef++]
                    else -> Unit
                }
            }
            if (id != null && data != null) {
                logResolve("queue-item-members", "metadata order ${propertyOrder} + positional getters")
                return ItemMembers(id, data)
            }
        }
        // Shape: id is the first int getter, data the first reference getter (declaration order).
        val shapeId = intGetters.firstOrNull()
        val shapeData = refGetters.firstOrNull()
        if (shapeId != null && shapeData != null) {
            logResolve("queue-item-members", "return-type shape")
            return ItemMembers(shapeId, shapeData)
        }
        logResolve("queue-item-members", "pinned accessor ids (metadata and shape unavailable)")
        return ItemMembers(
            itemId = requireMethod(type, ITEM_ID_FALLBACK) { isIntGetter(it) },
            itemData = requireMethod(type, ITEM_DATA_FALLBACK) { method ->
                method.parameterCount == 0 && !method.returnType.isPrimitive
            },
        )
    }

    private fun logResolve(what: String, how: String) {
        FoliaPlugin.logStatic("playback controls resolve $what: $how")
    }

    /**
     * Finds the classloader that can see the host classes: the Workshop API's loader first (the
     * host provides that class), then the context loader, then the plugin's own loader.
     */
    private fun locateControllerClass(): Pair<ClassLoader, Class<*>> {
        val candidates = LinkedHashSet<ClassLoader>()
        runCatching { WorkshopApi::class.java.classLoader }.getOrNull()?.let { candidates.add(it) }
        Thread.currentThread().contextClassLoader?.let { candidates.add(it) }
        FoliaPlaybackControls::class.java.classLoader?.let { candidates.add(it) }
        for (loader in candidates) {
            try {
                return loader to Class.forName(CONTROLLER_CLASS, false, loader)
            } catch (_: Throwable) {
                // Try the next loader; the full failure is logged below.
            }
        }
        throw ClassNotFoundException(
            "$CONTROLLER_CLASS not visible from ${candidates.size} classloader(s); " +
                "host classes are only present inside the SPW process"
        )
    }

    private fun loadClass(name: String, loader: ClassLoader): Class<*> = Class.forName(name, false, loader)

    /**
     * PlaybackController is a Kotlin `object`; its INSTANCE field also triggers the host class
     * initialisation (PlaybackService/BASS), which is why it is only touched from a live host.
     */
    private fun controllerInstance(controllerClass: Class<*>): Any {
        val instanceField: Field? = try {
            controllerClass.getDeclaredField(CONTROLLER_INSTANCE)
        } catch (_: Throwable) {
            controllerClass.declaredFields.firstOrNull { field ->
                Modifier.isStatic(field.modifiers) && field.type.isAssignableFrom(controllerClass)
            }
        }
        if (instanceField != null) {
            instanceField.trySetAccessible()
            instanceField.get(null)?.let { return it }
        }
        // Last resort: a static no-arg accessor/factory returning the object.
        for (method in controllerClass.methods) {
            if (!Modifier.isStatic(method.modifiers) || method.parameterCount != 0) continue
            if (!controllerClass.isAssignableFrom(method.returnType)) continue
            try {
                method.trySetAccessible()
                method.invoke(null)?.let { return it }
            } catch (_: Throwable) {
                // Keep looking.
            }
        }
        throw IllegalStateException("$CONTROLLER_CLASS has no reachable INSTANCE")
    }

